#!/usr/bin/env python3
"""Generate the standalone review from the actual iOS sources. No parallel app implementation."""
from pathlib import Path
import base64
import sys

root = Path(__file__).resolve().parent.parent

def generate():
    sources = sorted((root / 'CareVoice').rglob('*.swift'))
    imports = sorted({line for path in sources for line in path.read_text(encoding='utf-8').splitlines() if line.startswith('import ')})
    text = '''// GENERATED by scripts/sync_swift_review.py. Edit CareVoice/ sources, then regenerate.
// Complete native iPhone app, iOS 17+. Add ONLY this Swift file to a new iOS target.
// Set microphone and speech-recognition usage descriptions in the target's Info settings.
// JSON content is embedded below. Add carevoice-family-hd.mp4/.jpg and google-g.png
// from CareVoice/Resources/Media to retain the same welcome artwork as the app.
// This is SwiftUI, not a web wrapper. Supabase uses the same public configuration as mobile/.
// Server email-delivery/confirmation restrictions apply equally to both clients.

''' + '\n'.join(imports) + '\n\n'
    for path in sources:
        body = '\n'.join(line for line in path.read_text(encoding='utf-8').splitlines() if not line.startswith('import '))
        text += '// MARK: - ' + path.relative_to(root).as_posix() + '\n' + body + '\n\n'
    # Native bundle loader falls back to exactly these same packaged resources.
    resources = sorted(p for p in (root / 'CareVoice/Resources').rglob('*.json') if '.xcassets' not in str(p))
    entries = ['        "' + p.stem + '": "' + base64.b64encode(p.read_bytes()).decode() + '"' for p in resources]
    text = text.replace('static let embedded: [String: String] = [:]', 'static let embedded: [String: String] = [\n' + ',\n'.join(entries) + '\n    ]')
    return text.rstrip() + "\n"

target = root / 'review/CareVoiceComplete.swift'
content = generate()
if '--check' in sys.argv:
    if target.read_text(encoding='utf-8') != content:
        raise SystemExit('Swift review is stale; run python scripts/sync_swift_review.py')
else:
    target.write_text(content, encoding='utf-8')
survey = (root / 'CareVoice/Features/Survey.swift').read_text(encoding='utf-8')
models = (root / 'CareVoice/Core/Models.swift').read_text(encoding='utf-8')
language = models[models.index('enum AppLanguage:'):models.index('enum JourneyStage:')]
survey = '// GENERATED from CareVoice/Features/Survey.swift; standalone survey preview.\n' + survey + '\n' + language
survey = survey.rstrip() + '\n'
survey_target = root / 'review/CareVoiceSurveyReview.swift'
if '--check' in sys.argv:
    if survey_target.read_text(encoding='utf-8') != survey: raise SystemExit('Survey review is stale')
else: survey_target.write_text(survey, encoding='utf-8')
print('Swift review matches native app sources.')
